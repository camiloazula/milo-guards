//! The `Reach` of a POSIX line that only reads: `Workspace` when every read
//! stays in a workspace folder or a temporary folder, `Beyond` for a place
//! beyond them or a secret, and `Unknown` (never a reach) for what cannot be
//! placed. One test per set of paths: the plain workspace, other working
//! directories, a protected `.agent` at its root (a protected path is the
//! workspace's own: protecting it is about writes), the home folder as the
//! workspace and `~/.config` as the workspace (a secret is not the project's,
//! so reading everything below it is beyond). The plain readers of the plain
//! workspace are in `effect.rs`; PowerShell and cmd are in `reach_windows.rs`.

mod common;

use common::{check_effect, posix};
use milo_guards_shell::{effect, Effect, Paths, Protected, Reach, Shell};

const STAYS: Effect = Effect::ReadsOnly(Reach::Workspace);
const BEYOND: Effect = Effect::ReadsOnly(Reach::Beyond);

const AGENT: &str = "the agent's settings";

/// A POSIX machine whose agent runs in `cwd`, in the workspace
/// `/home/me/work/repo`.
fn posix_in(cwd: &str) -> Paths {
    Paths::new(cwd, "/home/me", ["/home/me/work/repo"])
}

/// The plain workspace with a protected `.agent` folder at its root.
fn agent() -> Paths {
    posix().with_protected([Protected::folder("/home/me/work/repo/.agent", AGENT)])
}

/// A POSIX machine whose workspace is the home folder.
fn posix_home() -> Paths {
    Paths::new("/home/me", "/home/me", ["/home/me"])
}

/// A POSIX machine whose workspace is `~/.config`, which holds `gh`'s login.
fn posix_config() -> Paths {
    Paths::new("/home/me/.config", "/home/me", ["/home/me/.config"])
}

