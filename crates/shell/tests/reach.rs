//! Every probe the review of `Reach` ran, kept as a row so a later fix cannot
//! reopen one. Each is read in the workspaces that matter: one with nothing
//! protected in it, one with a protected `.agent` at its root (a protected
//! path is the workspace's own: protecting it is about writes), one that is
//! the home folder and one that holds a folder of logins (a secret is not the
//! project's, so reading everything below it is beyond). A row's verdict is
//! what the rule gives: `Beyond` for a place beyond the workspace or a secret,
//! `Workspace` for the rest, `Unknown` for what cannot be read.

mod common;

use common::{check_effect, posix, windows};
use milo_guards_shell::{Effect, Paths, Protected, Reach, Shell};

const STAYS: Effect = Effect::ReadsOnly(Reach::Workspace);
const BEYOND: Effect = Effect::ReadsOnly(Reach::Beyond);

fn agent() -> Paths {
    posix().with_protected([Protected::folder(
        "/home/me/work/repo/.agent",
        "the agent's settings",
    )])
}

fn agent_windows() -> Paths {
    windows().with_protected([Protected::folder(
        r"C:\Users\me\dev\repo\.agent",
        "the agent's settings",
    )])
}

fn posix_home() -> Paths {
    Paths::new("/home/me", "/home/me", ["/home/me"])
}

fn posix_config() -> Paths {
    Paths::new("/home/me/.config", "/home/me", ["/home/me/.config"])
}

fn windows_home() -> Paths {
    Paths::new(r"C:\Users\me", r"C:\Users\me", [r"C:\Users\me"])
}

fn windows_roaming() -> Paths {
    Paths::new(
        r"C:\Users\me\AppData\Roaming",
        r"C:\Users\me",
        [r"C:\Users\me\AppData\Roaming"],
    )
}

