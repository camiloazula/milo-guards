/// The first Hangul syllable, and how many there are.
const HANGUL: u32 = 0xAC00;
const HANGUL_COUNT: u32 = 11_172;

/// The canonical combining class of `c`: 0 for a character that is not a
/// combining mark.
fn class(c: char) -> u8 {
    CLASSES
        .binary_search_by(|&(from, to, _)| {
            if to < c {
                std::cmp::Ordering::Less
            } else if from > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .map_or(0, |at| CLASSES[at].2)
}

/// The canonical decomposition of `name` (Unicode's NFD): each character
/// that has one replaced by it, a Hangul syllable by its jamo, and each run
/// of combining marks put in canonical order. Two names are canonically the
/// same when their decompositions are equal.
pub(crate) fn decomposed(name: &str) -> Vec<char> {
    let mut out: Vec<char> = Vec::with_capacity(name.len());
    for c in name.chars() {
        let code = u32::from(c);
        if (HANGUL..HANGUL + HANGUL_COUNT).contains(&code) {
            let syllable = code - HANGUL;
            let trailing = syllable % 28;
            let jamo = [
                Some(0x1100 + syllable / 588),
                Some(0x1161 + (syllable % 588) / 28),
                (trailing != 0).then_some(0x11A7 + trailing),
            ];
            out.extend(jamo.into_iter().flatten().filter_map(char::from_u32));
        } else if let Ok(at) = DECOMPOSED.binary_search(&c) {
            out.extend(DECOMPOSITIONS[at].chars());
        } else {
            out.push(c);
        }
    }
    let mut start = 0;
    while start < out.len() {
        if class(out[start]) == 0 {
            start += 1;
            continue;
        }
        let end = out[start..]
            .iter()
            .position(|&c| class(c) == 0)
            .map_or(out.len(), |len| start + len);
        out[start..end].sort_by_key(|&c| class(c));
        start = end;
    }
    out
}

/// `name` decomposed ([`decomposed`]) with its combining marks dropped: the
/// letters a pattern's `?` or class picks one by one, whichever spelling the
/// disk keeps (`caf?` picks `café` written either way). Names that differ
/// only in their marks are the same here, so it is used only where matching
/// too much fails closed.
pub(crate) fn without_marks(name: &str) -> String {
    decomposed(name)
        .into_iter()
        .filter(|&c| class(c) == 0)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_tables_are_in_order_and_whole() {
        assert!(DECOMPOSED.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(CLASSES
            .windows(2)
            .all(|pair| pair[0].1 < pair[1].0 && pair[0].0 <= pair[0].1));
        assert!(CLASSES
            .iter()
            .all(|&(from, to, class)| from <= to && class > 0));
        for (c, decomposition) in DECOMPOSED.iter().zip(DECOMPOSITIONS) {
            // A decomposition is another text, and fully decomposed already:
            // none of its characters decomposes again.
            assert_ne!(decomposition, c.to_string(), "{c:?}");
            assert!(
                decomposition
                    .chars()
                    .all(|part| DECOMPOSED.binary_search(&part).is_err()),
                "{c:?}"
            );
            assert_eq!(
                decomposed(decomposition),
                decomposition.chars().collect::<Vec<_>>()
            );
        }
    }

    #[test]
    fn spellings_that_are_canonically_the_same_decompose_the_same() {
        for (one, other) in [
            ("caf\u{e9}", "cafe\u{301}"),
            ("\u{c5}", "\u{212b}"),
            ("\u{c5}", "A\u{30a}"),
            ("\u{1e69}", "s\u{323}\u{307}"),
            ("\u{1e69}", "s\u{307}\u{323}"),
            ("\u{d55c}", "\u{1112}\u{1161}\u{11ab}"),
            ("\u{ac00}", "\u{1100}\u{1161}"),
            ("\u{3060}", "\u{305f}\u{3099}"),
            ("\u{f1}o", "n\u{303}o"),
        ] {
            assert_eq!(decomposed(one), decomposed(other), "{one:?} {other:?}");
        }
        for (one, other) in [
            ("caf\u{e9}", "cafe"),
            ("cafe\u{301}", "cafe\u{300}"),
            ("\u{fb01}", "fi"),
            ("\u{2126}", "\u{3a9}\u{301}"),
        ] {
            assert_ne!(decomposed(one), decomposed(other), "{one:?} {other:?}");
        }
        assert_eq!(decomposed("plain"), "plain".chars().collect::<Vec<_>>());
    }

    #[test]
    fn without_marks_keeps_the_letters_of_either_spelling() {
        assert_eq!(without_marks("caf\u{e9}"), "cafe");
        assert_eq!(without_marks("cafe\u{301}"), "cafe");
        assert_eq!(without_marks("\u{1e69}x"), "sx");
        assert_eq!(without_marks("\u{d55c}"), "\u{1112}\u{1161}\u{11ab}");
    }
}
